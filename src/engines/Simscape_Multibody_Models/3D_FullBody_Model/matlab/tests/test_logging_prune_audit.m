function tests = test_logging_prune_audit
%TEST_LOGGING_PRUNE_AUDIT MATLAB-side schema harness for issue #4397.
%
% This file is intentionally lightweight: CI hosts without a runnable Simulink
% 3D fullbody model can still use the Python static tests for the JSON schema,
% while MATLAB hosts can adapt the helper below to a loaded fixture model.

    tests = functiontests(localfunctions);
end


function testAuditSchemaHasRequiredFields(testCase)
    audit = local_minimal_audit_fixture();
    required = [ ...
        "schema_version", ...
        "source_model", ...
        "target_model", ...
        "measured_counts", ...
        "heuristic_estimates", ...
        "disabled_block_paths", ...
        "disabled_outport_paths", ...
        "category_breakdown", ...
        "downstream_signal_requirements", ...
        "candidates"];
    for i = 1:numel(required)
        verifyTrue(testCase, isfield(audit, required(i)), required(i));
    end
    verifyFalse(testCase, audit.heuristic_estimates.is_measured);
    verifyTrue(testCase, audit.downstream_signal_requirements.preserved);
end


function testDryRunCandidatesDoNotMutate(testCase)
    audit = local_minimal_audit_fixture();
    verifyTrue(testCase, audit.dry_run);
    for i = 1:numel(audit.candidates)
        verifyFalse(testCase, audit.candidates(i).mutated);
    end
end


