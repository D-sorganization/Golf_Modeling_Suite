    count = struct("value", 12, "measured", true);
    audit = struct( ...
        "schema_version", "3d_fullbody_logging_prune_audit.v1", ...
        "dry_run", true, ...
        "source_model", struct("path", "source.slx", "exists", false, "timestamp", "", "sha256", ""), ...
        "target_model", struct("path", "target.slx", "exists", false, "timestamp", "", "sha256", ""), ...
        "measured_counts", struct( ...
            "before", struct("total_blocks", count, "nonvirtual_blocks", count, "logged_signal_count", count), ...
            "after", struct("total_blocks", count, "nonvirtual_blocks", count, "logged_signal_count", count)), ...
        "heuristic_estimates", struct("disabled_signal_count", 1, "estimated_nonvirtual_block_savings", 1, "is_measured", false), ...
        "disabled_block_paths", strings(0, 1), ...
        "disabled_outport_paths", "model/ClubLocalForce", ...
        "category_breakdown", struct("local_global_club_duplicates", 1), ...
        "downstream_signal_requirements", struct("preserved", true, "allowlist", "ClubGlobalForce"), ...
        "candidates", struct("category", "local_global_club_duplicates", "kind", "outport", "path", "model/ClubLocalForce", "property", "SrcPortHandle.DataLogging", "action", "set logging off", "mutated", false));
end
