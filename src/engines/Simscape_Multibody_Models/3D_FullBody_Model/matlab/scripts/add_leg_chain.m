function out = add_leg_chain(model_name, opts)
%ADD_LEG_CHAIN  Add hip+knee+ankle+foot+contact subsystems to MODEL_NAME.
%
%   OUT = ADD_LEG_CHAIN(MODEL_NAME, OPTS) builds mirrored scripted leg
%   subsystems (Left/Right Leg Kinetically Driven) and a generated
%   Ground Contact Forces assembly.  The function declares the shared
%   ground/contact design surface so reruns report exactly which
%   Simscape-specific operations could not be completed headlessly.
%
%   Per leg:
%     * Hip Gimbal Joint (3 DOF) — input parameters
%       L/RHipStartPosition{X,Y,Z} (deg), L/RHipStartVelocity{X,Y,Z},
%       and 7-coefficient polynomial torque per axis named
%       L/RHip{X,Y,Z}{A..G} so that
%       getPolynomialParameterInfo() picks them up automatically.
%     * Knee Revolute Joint (1 DOF) — L/RKneeStartPosition,
%       L/RKneeStartVelocity, L/RKnee{A..G}.
%     * Ankle Universal Joint (2 DOF) — L/RAnkleStartPosition{X,Y},
%       L/RAnkleStartVelocity{X,Y}, L/RAnkle{X,Y}{A..G}.
%     * Upper-Leg, Lower-Leg, Foot rigid bodies (Cylindrical /
%       Cylindrical / Brick) sized from new model-workspace variables
%       (UpperLegLength, LowerLegLength, FootLength, plus masses).
%     * Foot ↔ Ground Spatial Contact Force (Sphere/Plane).
%
%   The function MUTATES the loaded model in place; caller must
%   ``save_system`` afterward.
%
%   Args:
%       MODEL_NAME (char/string)  loaded Simulink model name.
%       OPTS (struct)
%         .verbose          default true.
%         .dry_run          default false; build the block list but
%                           don't actually call add_block.
%         .skip_contact     default false; build joints + bodies but
%                           don't add the contact-force network.
%         .leg_root_path    default ``<MODEL_NAME>``; you can sandbox
%                           the new chain into a wrapper subsystem by
%                           passing e.g. ``<MODEL_NAME>/LowerBody``.
%
%   Returns:
%       OUT (struct)
%         .blocks_added         total block count delta.
%         .blocks_per_phase     per-phase counts.
%         .new_workspace_vars   names of new model-workspace variables
%                               (lengths/masses/inertias).  Caller can
%                               attach defaults via setVariable when
%                               creating the SimulationInput.
%
%   STATUS (2026-05-08):
%   This implementation slice creates mirrored generated leg subsystems
%   and a generated contact-force assembly using add_block / set_param /
%   add_line calls.  It deletes/rebuilds those generated subsystems on
%   every run so build_3d_fullbody is idempotent.  Simscape Multibody
%   library and mask names can vary by MATLAB release/license; those
%   operations are captured in OUT.operation_log and OUT.validation_status
%   instead of being silently ignored.
%
%   See also: BUILD_3D_FULLBODY, PRUNE_REDUNDANT_LOGGING,
%             VALIDATE_3D_FULLBODY.

    arguments
        model_name (1,1) string
        opts (1,1) struct = struct()
    end

    if ~isfield(opts, 'verbose');       opts.verbose       = true;  end
    if ~isfield(opts, 'dry_run');       opts.dry_run       = false; end
    if ~isfield(opts, 'skip_contact');  opts.skip_contact  = false; end
    if ~isfield(opts, 'leg_root_path')
        opts.leg_root_path = char(model_name);
    end

    if ~bdIsLoaded(char(model_name))
        error('add_leg_chain:notLoaded', ...
              'Model %s is not loaded.  Call load_system first.', model_name);
    end

    out = struct( ...
        'blocks_added',     0, ...
        'blocks_per_phase', struct( ...
            'workspace_vars',     0, ...
            'left_leg_subsystem', 0, ...
            'right_leg_subsystem',0, ...
            'ground_plane',       0, ...
            'contact_forces',     0), ...
        'new_workspace_vars', strings(0,1), ...
        'generated_blocks',  strings(0,1), ...
        'operation_log',     struct('operation', {}, 'target', {}, ...
                                    'status', {}, 'message', {}), ...
        'validation_status', "not_started");

    if opts.verbose
        fprintf('add_leg_chain: building mirrored scripted leg chains\n');
    end

    % ---- Phase 1: declare new model-workspace variables -------------
    % Anthropometric defaults (de-Leva male, ~1.78m subject):
    %   UpperLegLength = 0.435 m   (greater trochanter to knee)
    %   LowerLegLength = 0.430 m   (knee to lateral malleolus)
    %   FootLength     = 0.260 m   (heel to toe)
    %   Plus masses + simple cylindrical-uniform inertias.
    new_vars = local_default_workspace_vars();
    if ~opts.dry_run
        try
            ws = get_param(char(model_name), 'ModelWorkspace');
            f = fieldnames(new_vars);
            for k = 1:numel(f)
                if ~hasVariable(ws, f{k})
                    assignin(ws, f{k}, new_vars.(f{k}));
                    out.new_workspace_vars(end+1, 1) = string(f{k});
                end
            end
        catch ME
            warning('add_leg_chain:wsAddFailed', ...
                    'Could not add workspace variables: %s', ME.message);
        end
    else
        out.new_workspace_vars = string(fieldnames(new_vars));
    end
    out.blocks_per_phase.workspace_vars = numel(out.new_workspace_vars);

    % ---- Phase 2: create mirrored scripted leg chains ----------------
    left = local_build_leg(char(opts.leg_root_path), opts, 'L', 'Left', 260);
    out.blocks_per_phase.left_leg_subsystem = left.blocks_added;
    out.generated_blocks = left.generated_blocks;
    out.operation_log = [out.operation_log, left.operation_log];

    right = local_build_leg(char(opts.leg_root_path), opts, 'R', 'Right', 620);
    out.blocks_per_phase.right_leg_subsystem = right.blocks_added;
    out.generated_blocks = [out.generated_blocks; right.generated_blocks];
    out.operation_log = [out.operation_log, right.operation_log];

    % ---- Phase 3: create the shared ground/contact assembly ----------
    contact = local_build_ground_contact(char(opts.leg_root_path), opts);
    out.blocks_per_phase.ground_plane = contact.ground_plane_blocks;
    out.blocks_per_phase.contact_forces = contact.contact_force_blocks;
    out.generated_blocks = [out.generated_blocks; contact.generated_blocks];
    out.operation_log = [out.operation_log, contact.operation_log];

    out.blocks_added = out.blocks_per_phase.left_leg_subsystem + ...
        out.blocks_per_phase.right_leg_subsystem + ...
        out.blocks_per_phase.ground_plane + ...
        out.blocks_per_phase.contact_forces;
    failed = string({out.operation_log.status}) == "failed";
    if any(failed)
        out.validation_status = "partial_with_reported_failures";
    else
        out.validation_status = "left_leg_scripted";
    end

    if opts.verbose
        fprintf('  left leg generated blocks:  %d\n', ...
            out.blocks_per_phase.left_leg_subsystem);
        fprintf('  right leg generated blocks: %d\n', ...
            out.blocks_per_phase.right_leg_subsystem);
        fprintf('  contact generated blocks:   %d\n', ...
            out.blocks_per_phase.ground_plane + ...
            out.blocks_per_phase.contact_forces);
        fprintf('  validation_status: %s\n', out.validation_status);
        fprintf('  new model-workspace variables (default values queued): %d\n', ...
            out.blocks_per_phase.workspace_vars);
    end
end


% =====================================================================
function report = local_build_leg(root_path, opts, side, side_name, x0)
%LOCAL_BUILD_LEG  Delete/rebuild one generated leg subsystem.
    subsystem_name = sprintf('%s Leg Kinetically Driven', side_name);
    subsystem_path = sprintf('%s/%s', root_path, subsystem_name);

    report = struct( ...
        'blocks_added',     0, ...
        'generated_blocks', strings(0,1), ...
        'operation_log',    struct('operation', {}, 'target', {}, ...
                                   'status', {}, 'message', {}));

    if opts.dry_run
        specs = local_leg_block_specs(subsystem_path, side);
        report.blocks_added = numel(specs);
        report.generated_blocks = string({specs.dst})';
        report.operation_log(end+1) = local_log_entry( ...
            'dry_run', subsystem_path, 'ok', ...
            sprintf('Declared %s-leg block graph without mutating model.', side_name));
        return
    end

    if local_block_exists(subsystem_path)
        delete_block(subsystem_path);
        report.operation_log(end+1) = local_log_entry( ...
            'delete_block', subsystem_path, 'ok', ...
            sprintf('Removed prior generated %s-leg subsystem for idempotent rebuild.', side_name));
    end

    [ok, message] = local_try_add_block( ...
        'simulink/Ports & Subsystems/Subsystem', subsystem_path, ...
        {'Position', [x0 360 x0+310 620]});
    report.operation_log(end+1) = local_log_entry( ...
        'add_block', subsystem_path, local_status(ok), message);
    if ~ok
        return
    end
    report.generated_blocks(end+1, 1) = string(subsystem_path);

    specs = local_leg_block_specs(subsystem_path, side);
    for k = 1:numel(specs)
        spec = specs(k);
        [ok, message] = local_try_add_block(spec.src, spec.dst, spec.params);
        report.operation_log(end+1) = local_log_entry( ...
            'add_block', spec.dst, local_status(ok), message);
        if ok
            report.blocks_added = report.blocks_added + 1;
            report.generated_blocks(end+1, 1) = string(spec.dst);
        end
    end

    lines = local_leg_line_specs(side);
    for k = 1:size(lines, 1)
        [ok, message] = local_try_add_line(subsystem_path, lines{k,1}, lines{k,2});
        report.operation_log(end+1) = local_log_entry( ...
            'add_line', sprintf('%s: %s -> %s', subsystem_path, lines{k,1}, lines{k,2}), ...
            local_status(ok), message);
    end
end


