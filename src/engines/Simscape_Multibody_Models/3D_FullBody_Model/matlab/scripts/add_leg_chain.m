function report = local_build_ground_contact(root_path, opts)
%LOCAL_BUILD_GROUND_CONTACT  Delete/rebuild generated ground contact assembly.
    subsystem_name = 'Ground Contact Forces';
    subsystem_path = sprintf('%s/%s', root_path, subsystem_name);

    report = struct( ...
        'ground_plane_blocks',  0, ...
        'contact_force_blocks', 0, ...
        'generated_blocks',     strings(0,1), ...
        'operation_log',        struct('operation', {}, 'target', {}, ...
                                       'status', {}, 'message', {}));

    if opts.skip_contact
        report.operation_log(end+1) = local_log_entry( ...
            'skip', subsystem_path, 'skipped', ...
            'Contact generation disabled by opts.skip_contact.');
        return
    end

    if opts.dry_run
        specs = local_ground_contact_block_specs(subsystem_path);
        report.generated_blocks = string({specs.dst})';
        report.ground_plane_blocks = 1;
        report.contact_force_blocks = numel(specs) - 1;
        report.operation_log(end+1) = local_log_entry( ...
            'dry_run', subsystem_path, 'ok', ...
            'Declared ground/contact block graph without mutating model.');
        return
    end

    if local_block_exists(subsystem_path)
        delete_block(subsystem_path);
        report.operation_log(end+1) = local_log_entry( ...
            'delete_block', subsystem_path, 'ok', ...
            'Removed prior generated ground-contact subsystem for idempotent rebuild.');
    end

    [ok, message] = local_try_add_block( ...
        'simulink/Ports & Subsystems/Subsystem', subsystem_path, ...
        {'Position', [260 675 930 850]});
    report.operation_log(end+1) = local_log_entry( ...
        'add_block', subsystem_path, local_status(ok), message);
    if ~ok
        return
    end
    report.generated_blocks(end+1, 1) = string(subsystem_path);

    specs = local_ground_contact_block_specs(subsystem_path);
    for k = 1:numel(specs)
        spec = specs(k);
        [ok, message] = local_try_add_block(spec.src, spec.dst, spec.params);
        report.operation_log(end+1) = local_log_entry( ...
            'add_block', spec.dst, local_status(ok), message);
        if ok
            report.generated_blocks(end+1, 1) = string(spec.dst);
            if contains(string(spec.dst), "Ground_Plane")
                report.ground_plane_blocks = report.ground_plane_blocks + 1;
            elseif contains(string(spec.dst), "Contact_Force") || ...
                   contains(string(spec.dst), "GroundReaction")
                report.contact_force_blocks = report.contact_force_blocks + 1;
            end
        end
    end

    lines = local_ground_contact_line_specs();
    for k = 1:size(lines, 1)
        [ok, message] = local_try_add_line(subsystem_path, lines{k,1}, lines{k,2});
        report.operation_log(end+1) = local_log_entry( ...
            'add_line', sprintf('%s: %s -> %s', subsystem_path, lines{k,1}, lines{k,2}), ...
            local_status(ok), message);
    end
end


